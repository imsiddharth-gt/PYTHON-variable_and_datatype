"""Check Data Type
Create variables containing an integer, float, string, and boolean. Print their types using type()."""

integer_var = 42
float_var = 3.14
string_var = "Hello, Python!"
boolean_var = True

print(f"Variable: {integer_var:<18} | Type: {type(integer_var)}")
print(f"Variable: {float_var:<18} | Type: {type(float_var)}")
print(f"Variable: {string_var:<18} | Type: {type(string_var)}")
print(f"Variable: {boolean_var:<18} | Type: {type(boolean_var)}")

